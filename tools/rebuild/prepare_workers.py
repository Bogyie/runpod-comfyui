#!/usr/bin/env python3
"""Generate worker requirements from audited node configs without running hooks.

The native comfy-env worker protocol accepts ordinary venv interpreters. We use
frozen uv inputs instead of allowing the upstream installer to select a different
torch/CUDA combination. Optional omissions are explicit, reviewed in stack.yaml.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

import yaml

from audit_upstreams import audit
from snapshot_upstreams import ROOT


def package_name(requirement: str) -> str:
    match = re.match(r"([A-Za-z0-9][A-Za-z0-9_.-]*)", requirement)
    if not match:
        raise ValueError(f"Unsupported requirement: {requirement}")
    return re.sub(r"[-_.]+", "-", match[1]).lower()


def prepare(stack: dict, source_lock: dict, cache: Path, output: Path) -> dict:
    inspected = audit(source_lock, cache)
    policy = stack['workers']
    if policy['provider'] != 'uv-frozen-venv':
        raise ValueError('Unknown worker environment provider')
    base = []
    skipped = set(policy['skip_host_ui_packages'])
    for requirement in inspected['sources']['comfyui']['requirements']:
        if requirement.strip() and not requirement.lstrip().startswith('#'):
            if package_name(requirement) not in skipped:
                base.append(requirement)
    base.extend([f"comfy-env=={stack['isolation']['version']}", f"uv=={stack['resolver']['uv']}"])
    base.extend(f"{name}=={stack['gpu'][name]}" for name in ['torch','torchvision','torchaudio','xformers'])
    output.mkdir(parents=True, exist_ok=True)
    workers = {}
    for name, definition in policy['environments'].items():
        source = inspected['sources'][definition['source']]
        config = source['worker_configs'][definition['config']]
        if definition['cuda_policy'] != 'pytorch-sdpa':
            raise ValueError('CUDA extensions require separate artifact and kernel gates')
        if set(config.get('cuda', {}).get('packages', [])) != set(definition['optional_cuda_extensions']):
            raise ValueError(f'Unreviewed CUDA extension in {name}')
        if set(config.get('dependencies', {})) != set(definition['system_dependencies']):
            raise ValueError(f'Unreviewed system dependency in {name}')
        omissions = definition['optional_pypi_omissions']
        for package, evidence_file in omissions.items():
            if package not in config.get('pypi-dependencies', {}):
                raise ValueError(f'Unknown optional package {package}')
            if evidence_file not in source_lock['sources'][definition['source']]['files']:
                raise ValueError(f'Missing reviewed optional-package evidence: {evidence_file}')
        lines = ['# Generated by prepare_workers.py; do not edit.',
                 f"# {source['repository']}@{source['commit']}", *base, *source['requirements']]
        for package, spec in config.get('pypi-dependencies', {}).items():
            if package in omissions:
                lines.append(f'# Optional {package}: native local-file fallback in {omissions[package]}')
                continue
            if not isinstance(spec, str):
                raise ValueError(f'Unsupported worker dependency declaration: {package}={spec}')
            lines.append(package + ('' if spec == '*' else spec))
        for package, provider in definition['system_dependencies'].items():
            if provider == 'pypi':
                spec = config['dependencies'][package]
                lines.append(package + ('' if spec == '*' else spec))
            elif provider not in {'system','build-only'}:
                raise ValueError(f'Unreviewed provider for {package}')
        requirements = '\n'.join(lines) + '\n'
        (output / f'{name}.in').write_text(requirements)
        workers[name] = {
            **definition, 'commit': source['commit'],
            'requirements_sha256': hashlib.sha256(requirements.encode()).hexdigest(),
            'config_sha256': source_lock['sources'][definition['source']]['files'][definition['config']],
            'upstream_cuda_extensions_not_selected': config.get('cuda', {}).get('packages', []),
            'scope': 'Candidate requirements only; no node execution or GPU certification',
        }
    identity = {'schema_version':1, 'provider':policy['provider'], 'workers':workers}
    (output / 'workers.json').write_text(json.dumps(identity,indent=2,sort_keys=True)+'\n')
    return identity


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/inputs/workers')
    parser.add_argument('--verify-locks', action='store_true', help='Reject stale worker definitions, GPU pins or lock bytes')
    parser.add_argument('--record-locks', action='store_true', help='Record successfully resolved worker locks against their input identity')
    args = parser.parse_args()
    result = prepare(yaml.safe_load((ROOT/'build/stack.yaml').read_text()),
                     json.loads((ROOT/'locks/upstreams.lock.json').read_text()), ROOT/'.work/upstreams', args.output)
    lock_dir = ROOT / 'locks/workers'
    if args.record_locks and args.verify_locks:
        parser.error('Choose record-locks or verify-locks')
    if args.record_locks:
        result['gpu_lock_sha256'] = hashlib.sha256((ROOT/'locks/gpu/linux-amd64-cu128.txt').read_bytes()).hexdigest()
        for name, definition in result['workers'].items():
            filename = f'{name}-linux-amd64-cu128.txt'
            definition['lock_file'] = filename
            definition['lock_sha256'] = hashlib.sha256((lock_dir/filename).read_bytes()).hexdigest()
        (lock_dir/'manifest.json').write_text(json.dumps(result,indent=2,sort_keys=True)+'\n')
    if args.verify_locks:
        recorded = json.loads((lock_dir/'manifest.json').read_text())
        gpu_hash = hashlib.sha256((ROOT/'locks/gpu/linux-amd64-cu128.txt').read_bytes()).hexdigest()
        if recorded.get('provider') != result['provider'] or recorded.get('gpu_lock_sha256') != gpu_hash:
            raise ValueError('Worker provider/GPU lock changed without re-locking')
        if set(recorded['workers']) != set(result['workers']):
            raise ValueError('Worker set changed without re-locking')
        gpu_pins = dict(re.findall(r'^([A-Za-z0-9_.-]+)==([^\s\\]+)', (ROOT/'locks/gpu/linux-amd64-cu128.txt').read_text(), re.M))
        from link_gpu_packages import shared, canonical
        for name, definition in recorded['workers'].items():
            prepared = {key:value for key,value in definition.items() if key not in {'lock_file','lock_sha256'}}
            if prepared != result['workers'][name]:
                raise ValueError(f'Worker definition changed without re-locking: {name}')
            filename = definition['lock_file']
            if Path(filename).name != filename or filename in {'.','..'}:
                raise ValueError('Unsafe worker lock filename')
            data = (lock_dir/filename).read_bytes()
            if hashlib.sha256(data).hexdigest() != definition['lock_sha256']:
                raise ValueError(f'Worker lock bytes changed: {name}')
            worker_pins = dict(re.findall(r'^([A-Za-z0-9_.-]+)==([^\s\\]+)',data.decode(),re.M))
            for package, version in gpu_pins.items():
                if shared(canonical(package)) and worker_pins.get(package) != version:
                    raise ValueError(f'Worker GPU artifact pin disagrees with base: {name}/{package}')
    print(f"Prepared {len(result['workers'])} experimental worker inputs")


if __name__ == '__main__':
    main()
